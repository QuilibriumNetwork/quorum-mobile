import Expo
import React
import ReactAppDependencyProvider

@UIApplicationMain
public class AppDelegate: ExpoAppDelegate {
  var window: UIWindow?

  var reactNativeDelegate: ExpoReactNativeFactoryDelegate?
  var reactNativeFactory: RCTReactNativeFactory?

  public override func application(
    _ application: UIApplication,
    didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]? = nil
  ) -> Bool {
    AppDelegate.excludeAppDataFromBackup()

    let delegate = ReactNativeDelegate()
    let factory = ExpoReactNativeFactory(delegate: delegate)
    delegate.dependencyProvider = RCTAppDependencyProvider()

    reactNativeDelegate = delegate
    reactNativeFactory = factory
    bindReactNativeFactory(factory)

#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif

    return super.application(application, didFinishLaunchingWithOptions: launchOptions)
  }

  // Linking API
  public override func application(
    _ app: UIApplication,
    open url: URL,
    options: [UIApplication.OpenURLOptionsKey: Any] = [:]
  ) -> Bool {
    return super.application(app, open: url, options: options) || RCTLinkingManager.application(app, open: url, options: options)
  }

  // Universal Links
  public override func application(
    _ application: UIApplication,
    continue userActivity: NSUserActivity,
    restorationHandler: @escaping ([UIUserActivityRestoring]?) -> Void
  ) -> Bool {
    let result = RCTLinkingManager.application(application, continue: userActivity, restorationHandler: restorationHandler)
    return super.application(application, continue: userActivity, restorationHandler: restorationHandler) || result
  }

  // MARK: - Backup exclusion

  /// Shared with the Notification Service Extension and QuorumCryptoModule.getAppGroupPath.
  private static let appGroupId = "group.com.quilibrium.quorum-mobile.shared"

  /// App data never goes into an iCloud or Finder backup, or a Quick Start transfer.
  ///
  /// The iOS counterpart of `android:allowBackup="false"` plus
  /// `res/xml/data_extraction_rules.xml`. iOS backs up `Documents` and
  /// `Library/Application Support` by default, and that is where the MMKV stores
  /// (`Documents/mmkv`), the message database (`Documents/SQLite`) and the
  /// App Group mirror used by the notification extension live. Excluding a
  /// directory excludes everything under it, including files created later.
  /// SecureStore needs nothing here: its keychain items are
  /// `WHEN_UNLOCKED_THIS_DEVICE_ONLY`, which never leave the device.
  ///
  /// Runs on every launch, before React Native starts, so a directory that was
  /// recreated or restored gets the flag back. Not generated by Expo: a clean
  /// prebuild would drop it (see PREBUILD.md). Guarded by
  /// __tests__/iosBackupExclusion.test.ts.
  private static func excludeAppDataFromBackup() {
    let fileManager = FileManager.default
    var directories: [URL] = []
    directories += fileManager.urls(for: .documentDirectory, in: .userDomainMask)
    directories += fileManager.urls(for: .applicationSupportDirectory, in: .userDomainMask)
    if let appGroup = fileManager.containerURL(forSecurityApplicationGroupIdentifier: appGroupId) {
      directories.append(appGroup)
    }

    for var directory in directories {
      do {
        try fileManager.createDirectory(at: directory, withIntermediateDirectories: true)
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        try directory.setResourceValues(values)
      } catch {
        NSLog("[Quorum] could not exclude %@ from backup: %@", directory.path, error.localizedDescription)
      }
    }
  }
}

class ReactNativeDelegate: ExpoReactNativeFactoryDelegate {
  // Extension point for config-plugins

  override func sourceURL(for bridge: RCTBridge) -> URL? {
    // needed to return the correct URL for expo-dev-client.
    bridge.bundleURL ?? bundleURL()
  }

  override func bundleURL() -> URL? {
#if DEBUG
    return RCTBundleURLProvider.sharedSettings().jsBundleURL(forBundleRoot: ".expo/.virtual-metro-entry")
#else
    return Bundle.main.url(forResource: "main", withExtension: "jsbundle")
#endif
  }
}
